"""Count notices and ASDD electors by reason, gender and age band, per part and per AC."""

import sys
from pathlib import Path

import duckdb

NOTICE_REASONS = {
    "Unmapped with Last SIR": "unmapped",
    "Self Name Mismatch": "self_name_mismatch",
    "Parent Name Mismatch": "parent_name_mismatch",
    "Progeny Age Gap <9 Month": "progeny_age_gap_lt_9_months",
    "Parent Age Difference <15": "parent_age_diff_lt_15",
    "Progeny >= 6": "progeny_ge_6",
    "Parent Age difference >50": "parent_age_diff_gt_50",
    "Grandparent Age difference <40": "grandparent_age_diff_lt_40",
    "Parent Marked ineligible in Last SIR": "parent_ineligible",
    "": "none",  # Reason cell left blank in the PDF.
}
ASDD_REASONS = {
    "Permanently Shifted": "shifted",
    "Untraceable/Absent": "absent",
    "Death": "dead",
    "Already enrolled": "duplicate",
}
GENDERS = {"M": "male", "F": "female", "O": "third_gender"}
BANDS = ["18_19", "20_29", "30_39", "40_49", "50_59", "60_69", "70_79", "80_plus"]
BAND_SQL = """case when age < 20 then '18_19' when age < 30 then '20_29' when age < 40 then '30_39'
  when age < 50 then '40_49' when age < 60 then '50_59' when age < 70 then '60_69'
  when age < 80 then '70_79' else '80_plus' end"""
# Name one part-table column per gender and age band, such as female_40_49.
CELLS = [(g, b) for g in GENDERS.values() for b in BANDS]


def read(path: Path) -> str:
    # Set the CSV dialect explicitly because the auto-sniffer misreads asdd.csv.
    return f"read_csv('{path}', header=true, delim=',', quote='\"', escape='\"', all_varchar=true)"


def mapping(con: duckdb.DuckDBPyConnection, name: str, d: dict[str, str]) -> None:
    con.execute(f"create temp table {name} (text varchar, code varchar, ord int)")
    con.executemany(f"insert into {name} values (?, ?, ?)", [(t, c, i) for i, (t, c) in enumerate(d.items(), 1)])


README = """# Counts by reason, gender and age

Notices and ASDD electors split by reason, gender and age band at the same time, per part
(polling station) and per assembly constituency (AC). Generated by
`scripts/electoral-roll/aggregate_reasons.py` from the same person-level tables as the other files here.
Counts only; no names, EPIC numbers or other person-level fields.

Counting is done per part. The AC table is the sum of its parts.

## reasons_by_part.csv

{part_rows:,} rows: one per list, part and reason, for all {parts:,} current parts, zeros
included.

| Column | Meaning |
|---|---|
| list | `notice` or `asdd` |
| ac_no, part_no | Current part. Join to `notices_by_part.csv` or `asdd_by_part.csv` for names |
| reason | Reason code, or `all` for everyone on that list. Codes match the `reason_*` columns of the other files without the prefix |
| total | Electors, all genders and ages |
| male_18_19 ... third_gender_80_plus | Electors of that gender (as printed: M, F, O) in that age band. 24 columns that add up to `total` |

## reasons_by_ac.csv

{ac_rows:,} rows: every combination of list, AC, reason, gender and age band, zeros included.

| Column | Meaning |
|---|---|
| list | `notice` or `asdd` |
| ac_no, ac_name | Assembly constituency |
| reason | As above |
| gender | `male`, `female` or `third_gender` |
| age_band | `18_19`, `20_29`, ... `80_plus`, from the printed age |
| count | Electors |

## Reading both

ASDD electors have one reason each, so the reason rows add up to the `all` rows. A notice can
give more than one reason: it counts once under `all` and once under each reason it gives, so
notice reason rows can add up to more than `all`.

Rates: the draft roll counts by gender per AC are in
`data/electoral-roll/ac_uncollectable_31aug2026.csv`. There are no published draft roll counts per
part, and the draft roll has no ages, so part-level figures and age bands give shares within a
list, not rates.
"""


def main(notices_csv="processed/notices.csv", asdd_csv="processed/asdd.csv", out_dir="data/electoral-roll"):
    out = Path(out_dir)
    con = duckdb.connect()
    mapping(con, "notice_map", NOTICE_REASONS)
    mapping(con, "asdd_map", ASDD_REASONS)
    con.execute("create temp table genders (g varchar, gender varchar)")
    con.executemany("insert into genders values (?, ?)", list(GENDERS.items()))
    con.execute("create temp table bands (age_band varchar)")
    con.executemany("insert into bands values (?)", [(b,) for b in BANDS])

    for name, path, reason in [("n", notices_csv, "coalesce(trim(reason), '')"), ("a", asdd_csv, "reason")]:
        con.execute(f"""create temp table {name} as
            select ac_no::int as ac_no, trim(ac_name) as ac_name, part_no::int as part_no,
                   gender as g, age::int as age, {reason} as reason
            from {read(Path(path))}""")

    # Fail on any value the mappings do not cover so nothing drops out of the counts.
    for sql, what in [
        ("select distinct g from n union select distinct g from a except select g from genders", "gender"),
        ("select distinct reason from a except select text from asdd_map", "ASDD reason"),
        ("""select distinct trim(r) from n, unnest(string_split(reason, ',')) t(r) where reason <> ''
            except select text from notice_map""", "notice reason"),
        ("select 1 from n where age is null or age < 18 union select 1 from a where age is null or age < 18", "age"),
    ]:
        bad = con.execute(sql).fetchall()
        if bad:
            sys.exit(f"Unknown {what} values: {sorted(bad)}")

    band_n, band_a = BAND_SQL.replace("age", "n.age"), BAND_SQL.replace("age", "a.age")
    con.execute(f"""create temp table counted as
        select 'notice' as list, ac_no, part_no, 'all' as reason, g, {BAND_SQL} as age_band, count(*) as count
        from n group by all
        union all
        select 'notice', n.ac_no, n.part_no, m.code, n.g, {band_n}, count(*)
        from n, unnest(case when n.reason = '' then [''] else string_split(n.reason, ',') end) t(r)
        join notice_map m on m.text = trim(t.r) group by all
        union all
        select 'asdd', ac_no, part_no, 'all', g, {BAND_SQL}, count(*) from a group by all
        union all
        select 'asdd', a.ac_no, a.part_no, m.code, a.g, {band_a}, count(*)
        from a join asdd_map m on m.text = a.reason group by all""")

    con.execute("""create temp table lists as
        select 'notice' as list, 'all' as reason, 0 as ord
        union all select 'notice', code, ord from notice_map
        union all select 'asdd', 'all', 0
        union all select 'asdd', code, ord from asdd_map""")
    # Take parts from both lists, since some parts have ASDD electors but no notices.
    con.execute("""create temp table parts as
        select distinct ac_no, ac_name, part_no from n union select distinct ac_no, ac_name, part_no from a""")
    con.execute("""create temp table full_counts as
        select l.list, p.ac_no, p.ac_name, p.part_no, l.reason, l.ord, ge.g, ge.gender, b.age_band,
               coalesce(c.count, 0) as count
        from lists l cross join parts p cross join genders ge cross join bands b
        left join counted c
          on c.list = l.list and c.ac_no = p.ac_no and c.part_no = p.part_no and c.reason = l.reason
         and c.g = ge.g and c.age_band = b.age_band""")

    out.mkdir(parents=True, exist_ok=True)

    cells = ",\n        ".join(
        f"sum(count) filter (where gender = '{g}' and age_band = '{b}') as {g}_{b}" for g, b in CELLS)
    part_path = out / "reasons_by_part.csv"
    con.execute(f"""copy (
        select list, ac_no, part_no, reason, sum(count) as total,
        {cells}
        from full_counts group by list, ac_no, part_no, reason, ord
        order by list desc, ac_no, part_no, ord
    ) to '{part_path}' (header, delimiter ',')""")

    ac_path = out / "reasons_by_ac.csv"
    con.execute(f"""copy (
        select list, ac_no, ac_name, reason, gender, age_band, sum(count) as count
        from full_counts group by list, ac_no, ac_name, reason, ord, g, gender, age_band
        order by list desc, ac_no, ord, case g when 'M' then 0 when 'F' then 1 else 2 end, age_band
    ) to '{ac_path}' (header, delimiter ',')""")

    part_rows = len(con.execute(f"select 1 from read_csv('{part_path}')").fetchall())
    ac_rows = len(con.execute(f"select 1 from read_csv('{ac_path}')").fetchall())
    n_parts = len(con.execute("select 1 from parts").fetchall())
    (out / "README_reasons.md").write_text(README.format(part_rows=part_rows, parts=n_parts, ac_rows=ac_rows))
    totals = con.execute(
        f"select list, sum(count) from read_csv('{ac_path}') where reason = 'all' group by 1 order by 1").fetchall()
    print(f"{part_rows:,} rows -> {part_path}; {ac_rows:,} rows -> {ac_path}; {n_parts:,} parts; people: "
          + ", ".join(f"{k} {v:,}" for k, v in totals))


if __name__ == "__main__":
    main(*sys.argv[1:])
