"""Count notices per part and per AC from the person-level notices table."""

import hashlib
import sys
from pathlib import Path

import pandas as pd

# Map each reason as printed in the PDFs to its column name.
REASONS = {
    "Unmapped with Last SIR": "reason_unmapped",
    "Self Name Mismatch": "reason_self_name_mismatch",
    "Parent Name Mismatch": "reason_parent_name_mismatch",
    "Progeny Age Gap <9 Month": "reason_progeny_age_gap_lt_9_months",
    "Parent Age Difference <15": "reason_parent_age_diff_lt_15",
    "Progeny >= 6": "reason_progeny_ge_6",
    "Parent Age difference >50": "reason_parent_age_diff_gt_50",
    "Grandparent Age difference <40": "reason_grandparent_age_diff_lt_40",
    "Parent Marked ineligible in Last SIR": "reason_parent_ineligible",
}
NO_REASON = "reason_none"  # Used when the reason cell is blank in the PDF.
# Define age bands in years at the time of the list; 18-19 are first-time electors.
AGE_BANDS = [(18, 19), (20, 29), (30, 39), (40, 49), (50, 59), (60, 69), (70, 79), (80, None)]
AGE_COLS = [f"age_{lo}_{hi}" if hi else f"age_{lo}_plus" for lo, hi in AGE_BANDS]
COUNTS = ["notices_total", *REASONS.values(), NO_REASON,
          "notices_male", "notices_female", "notices_third_gender", *AGE_COLS]


def electors(notices_csv):
    df = pd.read_csv(notices_csv, dtype=str, keep_default_na=False)
    reasons = df["reason"].map(lambda cell: {r.strip() for r in cell.split(",") if r.strip()})
    unknown = sorted(set().union(*reasons) - REASONS.keys())
    if unknown:
        # Stop on an unknown reason so it cannot silently drop out of the counts.
        sys.exit(f"Unknown reason text, add it to REASONS: {unknown}")
    df["notices_total"] = 1
    for text, col in REASONS.items():
        df[col] = reasons.map(lambda rs: text in rs).astype(int)
    df[NO_REASON] = reasons.map(len).eq(0).astype(int)
    df["notices_male"] = df["gender"].eq("M").astype(int)
    df["notices_female"] = df["gender"].eq("F").astype(int)
    df["notices_third_gender"] = df["gender"].eq("O").astype(int)
    df["age"] = pd.to_numeric(df["age"], errors="coerce")
    for (lo, hi), col in zip(AGE_BANDS, AGE_COLS):
        df[col] = (df["age"] >= lo) & (df["age"] <= hi if hi else True)
        df[col] = df[col].astype(int)
    return df


def parts(manifest_csv):
    m = pd.read_csv(manifest_csv, dtype=str, keep_default_na=False)
    m = m[m["status"] == "ok"].drop_duplicates(["ac_no", "part_no"], keep="last")
    m["crawl_date"] = m["fetched_at"].str[:10]
    return m[["ac_no", "ac_name", "part_no", "part_name", "crawl_date", "sha1"]].rename(
        columns={"sha1": "source_sha1"})


def date_span(dates):
    lo, hi = min(dates), max(dates)
    return lo if lo == hi else f"{lo}/{hi}"


def by_part(people, part_list):
    stale = people.merge(part_list, on=["ac_no", "part_no"])
    stale = stale[stale["source_sha1_x"] != stale["source_sha1_y"]]
    if len(stale):
        sys.exit("processed/notices.csv does not match the PDFs in the manifest; re-run the parser.")
    counts = people.groupby(["ac_no", "part_no"])[COUNTS].sum()
    ages = people.groupby(["ac_no", "part_no"])["age"].median().rename("median_age")
    out = part_list.join(counts, on=["ac_no", "part_no"]).join(ages, on=["ac_no", "part_no"])
    out[COUNTS] = out[COUNTS].fillna(0).astype(int)
    out = out.sort_values(["ac_no", "part_no"], key=lambda s: s.astype(int))
    return out[["ac_no", "ac_name", "part_no", "part_name", *COUNTS, "median_age", "crawl_date", "source_sha1"]]


def by_ac(people, part_rows):
    g = part_rows.groupby(["ac_no", "ac_name"])
    out = g[COUNTS].sum()
    out.insert(0, "parts", g.size())
    out["median_age"] = people.groupby("ac_no")["age"].median().reindex(out.index.get_level_values("ac_no")).values
    out["crawl_date"] = g["crawl_date"].agg(date_span)
    # Fingerprint the AC with a sha1 of its part hashes, one per line, in part order.
    out["source_sha1"] = g["source_sha1"].agg(lambda s: hashlib.sha1("\n".join(s).encode()).hexdigest())
    out = out.reset_index()
    return out.sort_values("ac_no", key=lambda s: s.astype(int))


README = """# Notice aggregates

Counts of electors named in CEO Delhi's SIR 2026 "List of Persons to Whom Notices Have
Been Issued", built from the part-wise PDFs at
https://ceodelhinet.nic.in/ceodelhiweb/Notices_Issuedn.aspx. Unofficial; not affiliated
with CEO Delhi or the Election Commission of India.

Crawl date: {crawl_dates}. Coverage: {n_parts:,} parts in {n_acs} assembly constituencies,
{n_notices:,} electors.

Generated by `scripts/electoral-roll/aggregate_notices.py`. No names, EPIC numbers or other
person-level fields are stored here.

## notices_by_part.csv

One row per part (polling station), using the new part numbers (14,947 parts after
rationalisation).

| Column | Meaning |
|---|---|
| ac_no, ac_name | Assembly constituency |
| part_no, part_name | Part number and name as listed on the notices page |
| notices_total | Electors named in the part's notice list |
| reason_* | Electors whose notice gives that reason (see below) |
| notices_male, notices_female, notices_third_gender | Electors printed as male (M), female (F) and third gender (O). They add up to notices_total |
| age_18_19 ... age_80_plus | Electors in each age band: 18-19, 20-29, 30-39, 40-49, 50-59, 60-69, 70-79, 80 and over. They add up to notices_total |
| median_age | Median age of the electors named, blank when there are none |
| crawl_date | Date (UTC) the part's PDF was downloaded |
| source_sha1 | SHA-1 of the downloaded PDF, to detect republished lists |

An elector can have more than one reason. They count once in notices_total and once in
each of their reason columns, so the reason columns can add up to more than notices_total.

| Column | Reason text in the PDF |
|---|---|
{reason_rows}
| reason_none | Reason cell left blank |

## notices_by_ac.csv

The same counts summed to each constituency, plus `parts` (number of parts). median_age
is the median over all electors in the AC, not a sum. crawl_date is one date, or a
`first/last` range when the AC's parts were downloaded across more than one day.
source_sha1 is the SHA-1 of the AC's part hashes joined with newlines in part order.

Every count is shown as counted, including small ones.
"""


def main(notices_csv="processed/notices.csv", manifest_csv="raw/notices_pdfs/manifest.csv",
         out_dir="data/electoral-roll"):
    people = electors(notices_csv)
    part_rows = by_part(people, parts(manifest_csv))
    ac_rows = by_ac(people, part_rows)
    n_notices = int(part_rows["notices_total"].sum())
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    part_rows.to_csv(out / "notices_by_part.csv", index=False)
    ac_rows.to_csv(out / "notices_by_ac.csv", index=False)
    (out / "README_notices.md").write_text(README.format(
        crawl_dates=date_span(part_rows["crawl_date"]).replace("/", " to "),
        n_parts=len(part_rows), n_acs=len(ac_rows), n_notices=n_notices,
        reason_rows="\n".join(f"| {col} | {text} |" for text, col in REASONS.items()),
    ), encoding="utf-8")
    print(f"{len(part_rows)} parts, {len(ac_rows)} ACs, {n_notices} notices -> {out}/")


if __name__ == "__main__":
    main(*sys.argv[1:])
